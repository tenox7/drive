/* The gear parameter has range -1 (reverse) to 5 (5th) */
float engine_efficiency(
    int gear,
    float speed,
    VEHICLE_AUXDATA *vaux)
{
    float x,eff,min;
    int i;

    if (gear == 0) return(0.0);
    /* else */

    min =  0.5 * IDLE_RPM / vaux->peak_power_rpm;
    if ((x = 0.5 * speed / vaux->gear_best_speed[gear+NEUTRAL_GEAR]) < min)
	x = min;
    else if (x > 1.0) x = 1.0;

    if ((i = x * SINTABLE_GRANULARITY) < 0) i = 0;
    else if (i > (SINTABLE_GRANULARITY-1)) i = (SINTABLE_GRANULARITY-1);

    eff = (1.0 - vaux->two_peak_power/2.0) * sintable[i]
	+ x * vaux->two_peak_power;

    if (gear > 0) return(eff);
    else return(-eff);
}
